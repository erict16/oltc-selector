// Writes lib/activity.ts from git history: commits per day since the first
// commit. The release-notes page draws it as a bar chart, to show how often
// the app changes. Run before a release: npm run gen:activity
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const out = execFileSync("git", ["log", "--format=%ad", "--date=short"], {
  encoding: "utf8",
});
const counts = {};
for (const day of out.split("\n").filter(Boolean)) counts[day] = (counts[day] ?? 0) + 1;
const days = Object.keys(counts).sort();
const total = days.reduce((n, d) => n + counts[d], 0);

const body = `// Generated by scripts/gen-activity.mjs from git history. Do not edit.
// Re-run before a release: npm run gen:activity

/** First and last day with a commit, YYYY-MM-DD. */
export const ACTIVITY_FROM = ${JSON.stringify(days[0])};
export const ACTIVITY_TO = ${JSON.stringify(days[days.length - 1])};
/** All commits in the repository. */
export const COMMIT_TOTAL = ${total};
/** Commits per day; days with none are left out. */
export const COMMITS_PER_DAY: Record<string, number> = ${JSON.stringify(counts, null, 2)};
`;
writeFileSync(resolve(import.meta.dirname, "../lib/activity.ts"), body);
console.log(`lib/activity.ts: ${total} commits on ${days.length} days, ${days[0]} to ${days.at(-1)}`);
