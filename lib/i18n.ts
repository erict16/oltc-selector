export type Lang = "zh" | "en" | "vi" | "es" | "tr" | "ru";

export const LANG_OPTIONS: { id: Lang; label: string; short: string }[] = [
  { id: "zh", label: "中文", short: "中文" },
  { id: "en", label: "English", short: "EN" },
  { id: "vi", label: "Tiếng Việt", short: "VI" },
  { id: "es", label: "Español", short: "ES" },
  { id: "tr", label: "Türkçe", short: "TR" },
  { id: "ru", label: "Русский", short: "RU" },
];

const LANG_STORAGE_KEY = "oltc-selector-lang";

function isLang(v: string | null): v is Lang {
  return LANG_OPTIONS.some((o) => o.id === v);
}

function readStoredLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY);
    if (isLang(v)) return v;
  } catch {
    /* private mode / blocked storage */
  }
  return "zh";
}

let appLang: Lang = "zh";
if (typeof window !== "undefined") {
  appLang = readStoredLang();
}
const langSubs = new Set<() => void>();

export function setAppLang(l: Lang) {
  if (l === appLang) return;
  appLang = l;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, l);
  } catch {
    /* ignore */
  }
  langSubs.forEach((fn) => fn());
}

export function getAppLang(): Lang {
  return appLang;
}

export function getServerLang(): Lang {
  return "zh";
}

export function subscribeAppLang(fn: () => void) {
  langSubs.add(fn);
  return () => {
    langSubs.delete(fn);
  };
}

