const TABLES: Record<Lang, Dict> = { en, zh, vi, es, tr, ru };

export function t(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const table = TABLES[lang] ?? en;
  let s = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function currentLabel(lang: Lang, labelZh: string, labelEn: string): string {
  // Menu tiers are numeric symbols (≤ / >) — same in all Latin scripts; keep EN for non-zh
  return lang === "zh" ? labelZh : labelEn;
}
